import { type PackageNode, packageTree, walkPackageTree } from './package-tree';

export type ArchSpec = [label: string, value: string];

export type ArchNode = {
	id: string;
	title: string;
	type: string;
	usage: string;
	desc: string;
	/** Labeled facts from the public API / types — not a tag cloud. */
	specs: ArchSpec[];
	copyable?: boolean;
};

function defaultNode(node: PackageNode): ArchNode {
	if (node.kind === 'package') {
		return {
			id: node.id,
			title: 'Theorem',
			type: 'PACKAGE',
			usage: "import { defineProfile, runTurn } from '@theoremai/agents'",
			desc: 'Published npm/JSR package — root barrel plus every module under src/.',
			specs: [
				['root', 'mod.ts'],
				['tree', 'src/'],
				['version', '1.0.0'],
			],
			copyable: true,
		};
	}

	if (node.kind === 'folder') {
		return {
			id: node.id,
			title: node.label.replace(/\/$/, ''),
			type: 'FOLDER',
			usage: `// ${node.path}`,
			desc: `Directory \`${node.path}\` in the published package.`,
			specs: [
				['path', node.path],
				['files', String(node.children?.length ?? 0)],
				['kind', 'folder'],
			],
		};
	}

	const exportPaths: Record<string, string> = {
		'mod.ts': '@theoremai/agents',
		'src/kernel/mod.ts': '@theoremai/agents/kernel',
		'src/providers/mod.ts': '@theoremai/agents/providers',
		'src/providers/local/mod.ts': '@theoremai/agents/providers/local',
		'src/guardrails/mod.ts': '@theoremai/agents/guardrails',
		'src/observability/mod.ts': '@theoremai/agents/observability',
		'src/host/mod.ts': '@theoremai/agents/host',
		'src/cli/index.ts': '@theoremai/agents/cli',
		'src/presets/mod.ts': '@theoremai/agents/presets',
		'src/presets/google.ts': '@theoremai/agents/presets/google',
	};
	const entry = exportPaths[node.path];

	return {
		id: node.id,
		title: node.label,
		type: entry ? 'BARREL' : 'FILE',
		usage: entry ? `import { … } from '${entry}'` : `// Internal — ${node.path}`,
		desc: entry
			? `Public barrel \`${node.path}\` — re-export entry for \`${entry}\`.`
			: `Source file \`${node.path}\`. Shipped in the package; not a separate export path.`,
		specs: [
			['path', node.path],
			['export', node.path in exportPaths ? exportPaths[node.path] : 'none'],
			['kind', 'file'],
		],
		copyable: Boolean(entry),
	};
}

