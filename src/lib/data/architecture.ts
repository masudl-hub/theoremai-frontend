function buildArchitectureMap(): Record<string, ArchNode> {
	const map: Record<string, ArchNode> = {};
	walkPackageTree(packageTree, (node) => {
		map[node.id] = ARCH_OVERRIDES[node.id] ?? defaultNode(node);
	});
	return map;
}

