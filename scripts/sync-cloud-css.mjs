import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { cloudParade, cloudParadeSparse } from '../src/lib/data/clouds.ts';
import { cloudParadeCss } from '../src/lib/data/cloud-styles.ts';
import { useArtSceneCloudCss } from '../src/lib/data/use-art-clouds.ts';

const outDir = fileURLToPath(new URL('../src/lib/styles/', import.meta.url));
const outFile = fileURLToPath(new URL('../src/lib/styles/cloud-placements.css', import.meta.url));
const appCssFile = fileURLToPath(new URL('../src/app.css', import.meta.url));
mkdirSync(outDir, { recursive: true });

const header = '/* Generated by scripts/sync-cloud-css.mjs — do not edit by hand. */\n';
const css = `${[cloudParadeCss(cloudParade), cloudParadeCss(cloudParadeSparse), useArtSceneCloudCss()].join('\n\n')}\n`;
writeFileSync(outFile, header + css);

const importLine = '@import "./lib/styles/cloud-placements.css";';
let appCss = readFileSync(appCssFile, 'utf8');
if (!appCss.includes(importLine)) {
	appCss = appCss.replace(
		'@import "tailwindcss";\n',
		`@import "tailwindcss";\n${importLine}\n`,
	);
	writeFileSync(appCssFile, appCss);
}
